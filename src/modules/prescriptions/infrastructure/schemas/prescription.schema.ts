import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document } from 'mongoose';
import { PrescriptionStatus } from '../../domain/enums/prescription-status.enum';

export type PrescriptionDocument = PrescriptionSchemaClass & Document<string>;

@Schema({ _id: false })
export class PrescriptionItemSchemaClass {
  @Prop({ required: true, type: String })
  medicationName: string;

  @Prop({ required: true, type: String })
  dosage: string;

  @Prop({ required: true, type: String })
  frequency: string;

  @Prop({ required: true, type: Number })
  durationDays: number;

  @Prop({ type: Number })
  quantity?: number;

  @Prop({ type: String })
  route?: string;

  @Prop({ type: String })
  instructions?: string;
}
export const PrescriptionItemSchema = SchemaFactory.createForClass(PrescriptionItemSchemaClass);

@Schema({ collection: 'prescriptions', timestamps: true })
export class PrescriptionSchemaClass {
  // The id is generated by the domain (UUID), not by MongoDB.
  @Prop({ type: String })
  _id: string;

  @Prop({ required: true, type: String, unique: true })
  prescriptionCode: string;

  @Prop({ required: true, type: String, index: true })
  appointmentId: string;

  @Prop({ required: true, type: String, index: true })
  patientId: string;

  @Prop({ required: true, type: String, index: true })
  doctorId: string;

  @Prop({ required: true, type: String })
  doctorClinicId: string;

  @Prop({ type: [PrescriptionItemSchema], default: [] })
  items: PrescriptionItemSchemaClass[];

  @Prop({ type: String })
  diagnosis?: string;

  @Prop({ type: String })
  notes?: string;

  @Prop({ required: true, enum: PrescriptionStatus, default: PrescriptionStatus.ACTIVE })
  status: PrescriptionStatus;

  @Prop({ required: true, type: Date })
  issuedAt: Date;

  @Prop({ required: true, type: Date })
  validUntil: Date;

  @Prop({ type: String })
  cancellationReason?: string;

  @Prop({ type: String })
  cancelledBy?: string;

  @Prop({ type: Date })
  cancelledAt?: Date;
}

export const PrescriptionSchema = SchemaFactory.createForClass(PrescriptionSchemaClass);

// Patient history (the main read path) and doctor "issued by me" listing.
PrescriptionSchema.index({ patientId: 1, issuedAt: -1 });
PrescriptionSchema.index({ doctorId: 1, issuedAt: -1 });
